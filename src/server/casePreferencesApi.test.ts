import crypto from "node:crypto";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import request from "supertest";
import { afterEach, beforeEach, expect, it } from "vitest";
import { createApp } from "./app";
import { FileUserStore } from "./userStore";
import { FileCasePreferencesStore, validateCasePreference } from "./casePreferencesStore";
import { MemoryStateStore } from "./store";
import { rudderowExample } from "../shared/casePreferences";
let directory: string;
beforeEach(async () => { directory = await fs.mkdtemp(path.join(os.tmpdir(), "case-preferences-")); });
afterEach(async () => { await fs.rm(directory, { recursive: true, force: true }); });
it("enforces grant, view, edit, and immediate revocation with durable saves and stale-write protection", async () => {
  const users = new FileUserStore(path.join(directory, "users.json"));
  await users.createUser({ username: "preferences-admin", role: "admin", password: "test-password" });
  await users.createUser({ username: "preferences-reader", password: "test-password" });
  const filePath = path.join(directory, "cards.json");
  const app = createApp(new MemoryStateStore(), { userStore: users, casePreferencesStore: new FileCasePreferencesStore(filePath) });
  async function login(username: string) { return (await request(app).post("/api/auth/login").send({ username, password: "test-password" }).expect(200)).body.token; }
  const admin = await login("preferences-admin"), reader = await login("preferences-reader");
  const auth = (token: string) => `Bearer ${token}`;
  await request(app).get("/api/case-preferences").expect(401);
  await request(app).get("/api/case-preferences").set("authorization", auth(reader)).expect(403);
  await request(app).patch("/api/users/preferences-reader").set("authorization", auth(reader)).send({ casePreferencesAccess: "edit" }).expect(403);
  const result = await request(app).post("/api/case-preferences").set("authorization", auth(admin)).send({ card: rudderowExample() }).expect(201);
  const card = result.body.card;
  expect((await new FileCasePreferencesStore(filePath).list())[0].items).toEqual(card.items);
  await request(app).patch("/api/users/preferences-reader").set("authorization", auth(admin)).send({ casePreferencesAccess: "view" }).expect(200);
  await request(app).get("/api/case-preferences").set("authorization", auth(reader)).expect(200);
  await request(app).post("/api/case-preferences").set("authorization", auth(reader)).send({ card: rudderowExample() }).expect(403);
  await request(app).delete(`/api/case-preferences/${card.id}`).set("authorization", auth(reader)).send({ expectedRevision: 1 }).expect(403);
  await request(app).patch("/api/users/preferences-reader").set("authorization", auth(admin)).send({ casePreferencesAccess: "edit" }).expect(200);
  const updated = await request(app).put(`/api/case-preferences/${card.id}`).set("authorization", auth(reader)).send({ card: { ...card, notes: "Updated" }, expectedRevision: 1 }).expect(200);
  expect(updated.body.card.revision).toBe(2);
  await request(app).put(`/api/case-preferences/${card.id}`).set("authorization", auth(admin)).send({ card, expectedRevision: 1 }).expect(409);
  await request(app).delete(`/api/case-preferences/${card.id}`).set("authorization", auth(admin)).send({ expectedRevision: 1 }).expect(409);
  await request(app).patch("/api/users/preferences-reader").set("authorization", auth(admin)).send({ casePreferencesAccess: "none" }).expect(200);
  await request(app).get("/api/case-preferences").set("authorization", auth(reader)).expect(403);
  await request(app).put(`/api/case-preferences/${card.id}`).set("authorization", auth(reader)).send({ card, expectedRevision: 2 }).expect(403);
  await request(app).delete(`/api/case-preferences/${card.id}`).set("authorization", auth(admin)).send({ expectedRevision: 2 }).expect(204);
  expect(await new FileCasePreferencesStore(filePath).list()).toEqual([]);
});
it("rejects dangling references, duplicate change targets, and empty preferences", () => {
  const invalid = rudderowExample();
  invalid.contingencies[0].changes.push({ id: crypto.randomUUID(), action: "remove", itemId: "missing" });
  expect(() => validateCasePreference(invalid)).toThrow("existing base item");
  invalid.contingencies[0].changes.pop();
  invalid.contingencies[0].changes.push({ id: "duplicate", action: "remove", itemId: "entry" });
  expect(() => validateCasePreference(invalid)).toThrow("only once");
  invalid.contingencies = []; invalid.items[0].preferences = [];
  expect(() => validateCasePreference(invalid)).toThrow("first preference");
});
it("serializes concurrent writes so exactly one edit wins", async () => {
  const store = new FileCasePreferencesStore(path.join(directory, "cards.json"));
  const card = await store.save(rudderowExample(), undefined, "admin");
  const results = await Promise.allSettled([store.save({ ...card, notes: "One" }, 1, "editor", card.id), store.save({ ...card, notes: "Two" }, 1, "editor", card.id)]);
  expect(results.filter((result) => result.status === "fulfilled")).toHaveLength(1);
  expect((await store.list())[0].revision).toBe(2);
});
it("persists shared procedure defaults separately from surgeon cards and enforces one default per procedure", async () => {
  const filePath = path.join(directory, "cards.json");
  const store = new FileCasePreferencesStore(filePath);
  const example = rudderowExample();
  const fallback = await store.save({ ...example, isDefault: true, surgeonName: "Ignored for defaults" }, undefined, "admin");
  expect(fallback.surgeonName).toBe("");
  expect(fallback.isDefault).toBe(true);
  expect(fallback.items.find((item) => item.id === "entry")?.group).toBe("Laparoscopic trocars");
  await expect(store.save({ ...example, isDefault: true, procedureName: ` ${example.procedureName.toUpperCase()} ` }, undefined, "admin")).rejects.toThrow("default card already exists");
  const custom = await store.save(example, undefined, "editor");
  expect(custom.isDefault).toBe(false);
  expect(await new FileCasePreferencesStore(filePath).list()).toHaveLength(2);
  await expect(store.save({ ...example, surgeonName: "John Rudderow" }, undefined, "editor")).rejects.toThrow("surgeon already has a card");
});
