// @vitest-environment jsdom
import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { beforeEach, afterEach, expect, it, vi } from "vitest";
import { CaseCardView, CasePreferencesTab } from "./CasePreferencesTab";
import { rudderowExample } from "../shared/casePreferences";
import { fetchCasePreferenceCards, saveCasePreferenceCard } from "./casePreferencesApi";
vi.mock("./casePreferencesApi", () => ({ fetchCasePreferenceCards: vi.fn(), saveCasePreferenceCard: vi.fn(), deleteCasePreferenceCard: vi.fn() }));
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
let root: Root, container: HTMLDivElement;
beforeEach(() => { container = document.createElement("div"); document.body.append(container); root = createRoot(container); vi.clearAllMocks(); });
afterEach(() => { act(() => root.unmount()); container.remove(); });
it("shows ordered alternatives and removes closure alternatives under the bypass contingency", () => {
  act(() => root.render(<CaseCardView card={rudderowExample()} />));
  const details = container.querySelector<HTMLDetailsElement>("details")!;
  expect(details.open).toBe(false);
  expect(details.querySelector("ol")?.textContent).toContain("Choice 2M-CLOSE with 0 Vicryl");
  act(() => container.querySelector<HTMLButtonElement>(".cp-contingency-toggle")!.click());
  act(() => container.querySelector<HTMLInputElement>('.cp-scenario input')!.click());
  expect(container.querySelector(".cp-replaced")?.textContent).toContain("12 mm Hasson port");
  expect(container.querySelector(".cp-removed")?.textContent).toContain("Carter Thompson");
  expect(container.querySelector("details")).toBeNull();
  act(() => container.querySelector<HTMLInputElement>(".cp-scenario input")!.click());
  expect(container.querySelector("details")).not.toBeNull();
});
it("blocks pull checks for conflicting contingencies and resets checks when a scenario changes", () => {
  const card = rudderowExample();
  card.contingencies.push({ id: "overlap", name: "Other entry", conditions: [], changes: [{ id: "change", action: "remove", itemId: "entry" }] });
  act(() => root.render(<CaseCardView card={card} />));
  act(() => container.querySelector<HTMLInputElement>(".cp-pull-check input")!.click());
  expect(container.querySelector(".cp-setup-summary")?.textContent).toContain("1 / 10 pulled");
  act(() => container.querySelector<HTMLButtonElement>(".cp-contingency-toggle")!.click());
  act(() => container.querySelector<HTMLInputElement>(".cp-scenario input")!.click());
  expect(container.querySelector(".cp-setup-summary")?.textContent).toContain("0 / 9 pulled");
  act(() => container.querySelectorAll<HTMLInputElement>(".cp-scenario input")[1].click());
  expect(container.querySelector('[role="alert"]')?.textContent).toContain("Resolve overlapping");
  expect(Array.from(container.querySelectorAll<HTMLInputElement>(".cp-pull-check input")).every((input) => input.disabled)).toBe(true);
});
it("keeps viewing access free of editing actions", async () => {
  vi.mocked(fetchCasePreferenceCards).mockResolvedValue([{ ...rudderowExample(), id: "card", revision: 1, updatedAt: "2026-10-13T12:00:00Z", updatedBy: "admin" }]);
  await act(async () => root.render(<CasePreferencesTab token="test" canEdit={false} attendings={[]} onToast={() => {}} />));
  act(() => container.querySelector<HTMLButtonElement>(".cp-card-result")!.click());
  expect(container.textContent).toContain("Laparoscopic appendectomy");
  expect(container.textContent).not.toContain("Edit card");
  expect(container.textContent).not.toContain("New case card");
});
it("preserves the editor draft after a failed save", async () => {
  vi.mocked(fetchCasePreferenceCards).mockResolvedValue([{ ...rudderowExample(), id: "card", revision: 1, updatedAt: "2026-10-13T12:00:00Z", updatedBy: "admin" }]);
  vi.mocked(saveCasePreferenceCard).mockRejectedValue(new Error("Another editor changed this card"));
  await act(async () => root.render(<CasePreferencesTab token="test" canEdit attendings={[]} onToast={() => {}} />));
  act(() => container.querySelector<HTMLButtonElement>(".cp-card-result")!.click());
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>("button")).find((button) => button.textContent?.includes("Edit card"))!.click());
  await act(async () => container.querySelector("form")!.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })));
  expect(container.querySelector('[role="alert"]')?.textContent).toContain("Another editor");
  expect(container.querySelector<HTMLInputElement>('input[list="cp-surgeons"]')?.value).toContain("Rudderow");
});
it("opens only the instrument selected for editing and keeps alternatives ordered", async () => {
  vi.mocked(fetchCasePreferenceCards).mockResolvedValue([{ ...rudderowExample(), id: "card", revision: 1, updatedAt: "2026-10-13T12:00:00Z", updatedBy: "admin" }]);
  await act(async () => root.render(<CasePreferencesTab token="test" canEdit attendings={[]} onToast={() => {}} />));
  act(() => container.querySelector<HTMLButtonElement>(".cp-card-result")!.click());
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>("button")).find((button) => button.textContent?.includes("Edit card"))!.click());
  const editors = container.querySelectorAll<HTMLDetailsElement>(".cp-edit-item");
  expect(Array.from(editors).every((editor) => !editor.open)).toBe(true);
  act(() => editors[7].querySelector<HTMLElement>("summary")!.click());
  expect(editors[7].open).toBe(true);
  expect(editors[0].open).toBe(false);
  const fields = editors[7].querySelectorAll<HTMLInputElement>(".cp-preference-input input");
  expect(fields[0].value).toContain("Carter Thompson");
  expect(fields[1].value).toContain("M-CLOSE");
  act(() => editors[7].querySelector<HTMLButtonElement>('[aria-label="Move choice 2 up"]')!.click());
  expect(editors[7].querySelector<HTMLInputElement>(".cp-preference-input input")?.value).toContain("M-CLOSE");
  expect(container.querySelector(".cp-preview details summary")?.textContent).toContain("M-CLOSE");
});
it("collapses the contingency list without deactivating selections and keeps removed rows in their original group", () => {
  act(() => root.render(<CaseCardView card={rudderowExample()} />));
  expect(container.querySelector(".cp-scenario")).toBeNull();
  const button = container.querySelector<HTMLButtonElement>(".cp-contingency-toggle")!;
  expect(button.getAttribute("aria-expanded")).toBe("false");
  act(() => button.click());
  expect(button.getAttribute("aria-pressed")).toBe("true");
  act(() => container.querySelector<HTMLInputElement>(".cp-scenario input")!.click());
  act(() => button.click());
  expect(container.querySelector(".cp-scenario")).toBeNull();
  expect(container.querySelector(".cp-active-scenario")?.textContent).toContain("Roux-en-Y");
  expect(container.querySelector(".cp-replaced")?.textContent).toContain("Hasson");
  const removed = container.querySelector(".cp-removed")!;
  expect(removed.closest(".cp-item-group")?.querySelector("h5")?.textContent).toBe("Closure");
  expect(removed.textContent).toContain("Do not pull");
  expect(removed.querySelector("details")).toBeNull();
  expect(container.textContent).not.toContain("Pull checks are temporary");
  expect(container.textContent).not.toContain("Select all applicable situations");
  expect(container.textContent).toContain("4-0 Vicryl");
  expect(container.textContent).toContain("Dermabond glue");
  act(() => button.click());
  expect(container.querySelector<HTMLInputElement>(".cp-scenario input")?.checked).toBe(true);
});
it("offers templates and only real surgeon cards in the copy picker", async () => {
  const own = { ...rudderowExample(), id: "own", revision: 1, updatedAt: "2026-10-13T12:00:00Z", updatedBy: "admin" };
  const fallback = { ...own, id: "default", isDefault: true, surgeonName: "", procedureName: "Laparoscopic cholecystectomy" };
  vi.mocked(fetchCasePreferenceCards).mockResolvedValue([own, fallback]);
  await act(async () => root.render(<CasePreferencesTab token="test" canEdit attendings={[]} onToast={() => {}} />));
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>("button")).find((button) => button.textContent?.trim() === "New case card")!.click());
  expect(container.querySelector(".cp-template-options")?.textContent).toContain("Laparoscopic");
  expect(container.querySelector(".cp-template-options")?.textContent).toContain("Empty");
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>(".cp-template-options button")).find((button) => button.textContent?.includes("Copy from other card"))!.click());
  expect(container.querySelectorAll(".cp-copy-picker .cp-card-result")).toHaveLength(1);
  expect(container.querySelector(".cp-copy-picker")?.textContent).not.toContain("cholecystectomy");
  act(() => container.querySelector<HTMLButtonElement>(".cp-copy-picker .cp-card-result")!.click());
  expect(container.querySelector<HTMLInputElement>('input[list="cp-surgeons"]')?.value).toBe("");
  expect(container.querySelector<HTMLInputElement>('input[list="cp-procedures"]')?.value).toBe("Laparoscopic appendectomy");
});
it("uses a flagged default when browsing a surgeon and customizes it without editing the shared default", async () => {
  const fallback = { ...rudderowExample(), id: "default", isDefault: true, surgeonName: "", revision: 1, updatedAt: "2026-10-13T12:00:00Z", updatedBy: "admin" };
  // A real surgeon's existing card supplies their library identity.
  const own = { ...fallback, id: "own", isDefault: false, surgeonName: "Dr. Example Surgeon", procedureName: "Other procedure" };
  vi.mocked(fetchCasePreferenceCards).mockResolvedValue([fallback, own]);
  await act(async () => root.render(<CasePreferencesTab token="test" canEdit attendings={[]} onToast={() => {}} />));
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>(".cp-browse-switch button")).find((button) => button.textContent === "By surgeon")!.click());
  const inherited = Array.from(container.querySelectorAll<HTMLButtonElement>(".cp-card-result")).find((button) => button.textContent?.includes("Laparoscopic appendectomy"))!;
  expect(inherited.textContent).toContain("Default");
  act(() => inherited.click());
  expect(container.querySelector(".cp-case-heading .cp-default-flag")?.textContent).toBe("Default card");
  expect(container.querySelector(".cp-card-toolbar")?.textContent).not.toContain("Copy card");
  act(() => Array.from(container.querySelectorAll<HTMLButtonElement>("button")).find((button) => button.textContent?.includes("Customize for surgeon"))!.click());
  expect(container.querySelector<HTMLInputElement>('input[list="cp-surgeons"]')?.value).toBe("Dr. Example Surgeon");
  expect(container.querySelector<HTMLInputElement>(".cp-default-choice input")?.checked).toBe(false);
});
